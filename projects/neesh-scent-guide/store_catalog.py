def format_perfume_catalog():
    """Return the fragrance facts in a compact form for the assistant prompt."""
    records = []
    for perfume in PERFUME_CATALOG:
        sizes = "; ".join(
            f"{item['size']} {item['price']} ({'listed in stock' if item['available'] else 'listed sold out'})"
            for item in perfume["sizes"]
        )
        records.append(
            "\n".join(
                (
                    f"{perfume['name']} — {perfume['description']}",
                    f"Top notes: {', '.join(perfume['top'])}.",
                    f"Heart notes: {', '.join(perfume['heart'])}.",
                    f"Base notes: {', '.join(perfume['base'])}.",
                    f"Best for: {', '.join(perfume['best_for'])}.",
                    f"Sizes and listed prices: {sizes}.",
                    f"Official product page: {CATALOG_SOURCE}/products/{perfume['handle']}.",
                )
            )
        )
    return "\n\n".join(records)
