def main() -> None:
    path = sys.argv[1] if len(sys.argv) > 1 else "ndr_model.joblib"
    resolver = NDRResolver.load(path)

    texts = [t for t, _ in CHALLENGE]
    gold = [g for _, g in CHALLENGE]
    decisions = [resolver.resolve(t) for t in texts]
    pred = [d.intent for d in decisions]
    conf = np.array([d.confidence for d in decisions])

    print("=" * 78)
    print("OUT-OF-DISTRIBUTION CHALLENGE SET (hand-written, unseen phrasings)")
    print("=" * 78)
    print(f"n = {len(CHALLENGE)}")
    print(f"Accuracy : {accuracy_score(gold, pred):.4f}")
    print(f"Macro F1 : {f1_score(gold, pred, average='macro', zero_division=0):.4f}\n")
    print(classification_report(gold, pred, digits=3, zero_division=0))

    # ------------------------------------------------------------------ #
    # Operational breakdown.
    #
    # Flat accuracy is the wrong metric for this system, because "escalated to
    # a human" is a *correct* outcome, not a misclassification. What actually
    # costs money is a wrong action executed with no human in the loop. So the
    # three buckets below are scored separately.
    # ------------------------------------------------------------------ #
    buckets = {"AUTO_EXECUTE": [0, 0], "REVIEW": [0, 0], "HUMAN_REQUIRED": [0, 0]}
    for g, d in zip(gold, decisions):
        b = buckets[d.mode]
        b[0] += 1
        b[1] += int(d.intent == g)

    n = len(CHALLENGE)
    print("Operational breakdown (what the system would actually have done):")
    print(f"{'mode':<16}{'volume':>9}{'share':>9}{'correct':>10}{'cost of an error':>26}")
    cost = {
        "AUTO_EXECUTE": "wrong action, no human",
        "REVIEW": "caught by reviewer",
        "HUMAN_REQUIRED": "none — human decides",
    }
    for mode, (tot, ok) in buckets.items():
        share = tot / n * 100
        acc = f"{ok / tot * 100:.1f}%" if tot else "—"
        print(f"{mode:<16}{tot:>9}{share:>8.1f}%{acc:>10}{cost[mode]:>26}")

    auto_tot, auto_ok = buckets["AUTO_EXECUTE"]
    print(f"\nHeadline: {(auto_tot - auto_ok)}/{n} replies "
          f"({(auto_tot - auto_ok) / n * 100:.1f}%) would receive a wrong action "
          f"with no human in the loop.")
    print("Every other error is either reviewed or escalated before anything happens.")

    print("\nSilent failures (auto-executed AND wrong — the only errors that hurt):")
    silent = [(t, g, d) for t, g, d in zip(texts, gold, decisions)
              if d.mode == "AUTO_EXECUTE" and d.intent != g]
    if not silent:
        print("  none")
    for text, g, d in silent:
        print(f"  {text!r}\n      gold={g}  pred={d.intent} @ {d.confidence:.2f}  "
              f"-> {d.action}")

    print("\nAll misclassifications (including safely-escalated ones):")
    for text, g, d in zip(texts, gold, decisions):
        if d.intent != g:
            print(f"  [{d.mode:<14}] {text!r}\n      gold={g}  pred={d.intent} "
                  f"({d.confidence:.2f})  action={d.action}")


if __name__ == "__main__":
    main()
